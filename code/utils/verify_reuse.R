#!/usr/bin/env Rscript
P <- "/data/workplace/wyx/oral_deconv_reference_20260707"
source(file.path(P,"code/utils/deconv_utils.R"))
S_gep <- readRDS(file.path(P,"results/models/S_oral_gepMeanCPM.rds"))
LM22  <- readRDS(file.path(P,"results/models/LM22.rds"))
d <- readRDS(file.path(P,"data/processed/bulk/GSE173078_linear.rds"))
bulk <- as.matrix(d$expr[, 1:4])
cat("=== DWLS dampened (reused) on oral signature ===\n")
fr <- deconv_dwls(bulk, S_gep, method="dampened", cores=4)
print(round(fr,3)); cat("rowSums:", round(rowSums(fr),3), "\n")
cat("\n=== DWLS dampened on LM22 (same solver) ===\n")
frl <- deconv_dwls(bulk, LM22, method="dampened", cores=4)
cat("LM22 dims:", dim(frl), " rowSums:", round(rowSums(frl),3), "\n")
cat("\n=== nnls (reused nnls pkg) ===\n")
frn <- deconv_nnls(bulk, S_gep); print(round(frn,3))
cat("\n=== bMIND source reuse ===\n")
print(load_bmind())
cat("bMIND formals:", paste(head(names(formals(bMIND)),8),collapse=","), "\n")
cat("[verify done]\n")
